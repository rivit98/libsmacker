/* Bytes of the video frame read back per frame - enough to touch it under the
 * sanitizers without turning a 16k x 16k header into a slow exec. */
#define FRAME_READ_MAX (1u << 20)

/*
 * Video decoding stays off for a frame dimension above this. The decoder
 * walks every 4x4 block row of the header's height, so w=0 h=0xff000000 is a
 * billion iterations per frame - a timeout, not a finding.
 */
#define VIDEO_DIM_MAX 4096

/*
 * Decoded output per test case - video pixels plus audio bytes - after which
 * decoding is switched off and the remaining frames are only walked. Both
 * decoders produce output without consuming input (an empty huff16 tree fills
 * the whole frame, an empty huff8 tree the whole DPCM buffer), so a 10 KB
 * input of ~1100 tiny frames could otherwise decode gigabytes: measured,
 * 640x480 took 620 ms and 4096x4096 27 s against a 200 ms exec timeout.
 * Decoding runs at ~6 ns per pixel, so 4M (13 full 640x480 frames) bounds a
 * test case near 30 ms.
 */
#define DECODE_BUDGET (1ul << 22)

/*
 * The audio_size header fields: seven little-endian 32-bit values from offset
 * 0x18, after the signature, width, height, frame count, frame rate and flags.
 * Each sizes the buffer the library allocates for that track, so it is the
 * most one frame can decode into it - an empty huff8 tree fills it without
 * consuming input, and a 3.9 GB audio_size is one header field away.
 */
#define AUDIO_SIZE_OFFSET 0x18

/* Track @t's audio_size. @data must hold the whole header: call it only after
 * smk_open_memory() succeeded, which read all of it. */
static unsigned long header_audio_size(const char *data, unsigned char t)
{
  const unsigned char *p = (const unsigned char *)data + AUDIO_SIZE_OFFSET + 4u * t;

  return (unsigned long)p[0] | (unsigned long)p[1] << 8 |
         (unsigned long)p[2] << 16 | (unsigned long)p[3] << 24;
}

static volatile unsigned int sink;

/*
 * Read back what the frame just decoded under @mask: the palette, the video
 * frame and each enabled audio track's buffer. The branch on the checksum is
 * what makes MSAN look at the bytes. A disabled track is skipped - its
 * buffer_size is whatever an earlier frame left there.
 *
 * Returns the frame's decoded output, for DECODE_BUDGET.
 */
static unsigned long consume_frame(smk s, unsigned char mask)
{
  const unsigned char *pal, *video, *audio;
  unsigned long w = 0, h = 0, n, i, decoded = 0;
  unsigned int sum = 0;
  unsigned char t;

  pal = smk_get_palette(s);
  if (pal)
    for (i = 0; i < 256 * 3; i++)
      sum += pal[i];

  video = smk_get_video(s);
  if ((mask & SMK_VIDEO_TRACK) && video && smk_info_video(s, &w, &h, NULL) >= 0) {
    decoded += w * h;
    n = w * h;
    if (n > FRAME_READ_MAX)
      n = FRAME_READ_MAX;
    for (i = 0; i < n; i++)
      sum += video[i];
  }

  /*
   * smk_get_audio_size() bytes are what the API says is there. An overflow
   * reported here is the library's: smk_render_audio() stores the DPCM
   * unpacked size before validating the chunk, and keeps it on error.
   */
  for (t = 0; t < 7; t++) {
    if (!(mask & (1u << t)))
      continue;
    audio = smk_get_audio(s, t);
    n = smk_get_audio_size(s, t);
    if (!audio)
      continue;
    decoded += n;
    for (i = 0; i < n; i++)
      sum += audio[i];
  }

  if (sum == 0x5a5a5a5a)
    sink++;

  return decoded;
}

/* Every track the file has, video included. */
#define ENABLE_ALL (SMK_VIDEO_TRACK | SMK_AUDIO_TRACK_0 | SMK_AUDIO_TRACK_1 | \
                    SMK_AUDIO_TRACK_2 | SMK_AUDIO_TRACK_3 | SMK_AUDIO_TRACK_4 | \
                    SMK_AUDIO_TRACK_5 | SMK_AUDIO_TRACK_6)

/* Past DECODE_BUDGET, disable every track: frames are still walked, not decoded. */
static void spend_budget(smk s, unsigned char *mask, unsigned long decoded)
{
  if (*mask && decoded >= DECODE_BUDGET) {
    *mask = 0;
    smk_enable_all(s, *mask);
  }
}

/*
 * The whole input is the .smk file. Its last byte also picks the seek target,
 * without being taken out of the file.
 *
 * Open from memory, read the header info, decode every frame in order the way
 * driver.c does, then seek on the same decoder - a player seeking
 * mid-playback.
 *
 * Tracks: every one the file has. smk_enable_all() ignores the audio bits of
 * tracks the file does not declare. Video stays off for a frame too tall or
 * too wide (VIDEO_DIM_MAX) or larger than DECODE_BUDGET on its own.
 *
 * DECODE_BUDGET is only checked between frames, so it also caps what a single
 * frame can declare: w*h video bytes plus every enabled track's audio_size.
 * Audio tracks are kept in order while that total fits, and a track that would
 * push it over stays off - one over the budget on its own always does.
 *
 * Decoding: smk_first(), then one smk_next() per frame, carrying on past a
 * frame that fails to render. With a ring frame the last smk_next() decodes
 * it; without one it returns SMK_DONE. Counting calls instead of looping on
 * SMK_MORE keeps this finite: smk_next() wraps around to frame 1 when a ring
 * frame's last frame fails. The frame count is bounded by the input - every
 * frame takes 5 header bytes - and the decoding work by DECODE_BUDGET, which
 * the seek shares.
 *
 * Seeking: smk_seek_keyframe() to the last byte modulo the frame count - an
 * index past the end is caller misuse, not a library bug - then that keyframe
 * and the frame after it.
 */
void test_decode(const char *data, size_t size) {
  unsigned long frame, frame_count = 0, w = 0, h = 0, audio_rate[7], decoded;
  unsigned long frame_bound, n;
  unsigned char y_scale_mode, channels[7], bitdepth[7], t;
  unsigned char track_mask = 0x7f; /* every track, if smk_info_audio() fails */
  unsigned char mask = ENABLE_ALL, seek_frame;
  double usf;
  smk s = NULL;

  CHECK(size >= 1);
  seek_frame = (unsigned char)data[size - 1];
  s = smk_open_memory((const unsigned char *)data, size);
  CHECK(s);

  CHECK(smk_info_all(s, &frame, &frame_count, &usf) >= 0);
  if (smk_info_video(s, &w, &h, &y_scale_mode) < 0 ||
      w > VIDEO_DIM_MAX || h > VIDEO_DIM_MAX || w * h > DECODE_BUDGET)
    mask &= (unsigned char)~SMK_VIDEO_TRACK;
  USE(smk_info_audio(s, &track_mask, channels, bitdepth, audio_rate));

  frame_bound = (mask & SMK_VIDEO_TRACK) ? w * h : 0;
  for (t = 0; t < 7; t++) {
    if (!(track_mask & (1u << t)))
      continue;
    n = header_audio_size(data, t);
    if (n > DECODE_BUDGET - frame_bound)
      mask &= (unsigned char)~(1u << t);
    else
      frame_bound += n;
  }
  smk_enable_all(s, mask);

  smk_first(s);
  decoded = consume_frame(s, mask);
  for (unsigned long n = 0; n < frame_count; n++) {
    spend_budget(s, &mask, decoded);
    smk_next(s);
    decoded += consume_frame(s, mask);
  }

  CHECK(frame_count > 0);
  spend_budget(s, &mask, decoded);
  CHECK(smk_seek_keyframe(s, seek_frame % frame_count) >= 0);
  decoded += consume_frame(s, mask);
  spend_budget(s, &mask, decoded);
  smk_next(s);
  consume_frame(s, mask);

out:
  if (s)
    smk_close(s);
}

void test_smk(const char *data, size_t size) {
  T2(test_decode);
}

int LLVMFuzzerTestOneInput(const uint8_t *data, size_t size) {
  if (size == 0) return 0;

  G(test_decode);

  if (__builtin_expect(tc_filter != NULL, 0) && !tc_filter_matched) {
    fprintf(real_stderr, "TC=%s does not name any test case\n", tc_filter);
    exit(1);
  }

  /*
   * Per-input leak check: afl-cc defines __AFL_LEAK_CHECK() only for an
   * AFL_USE_LSAN build (recoverable check, _exit(23) on a leak, which AFL
   * saves as a crash); it expands to nothing everywhere else.
   */
#ifdef __AFL_LEAK_CHECK
  __AFL_LEAK_CHECK();
#endif

  return 0;
}

